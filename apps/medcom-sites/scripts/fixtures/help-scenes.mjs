export async function captureHelpScenes({ page, device, visit, capture, field, select, fillField }) {
  const button = name => page.getByRole('button', { name, exact: true });
  const top = locator => locator.evaluate(node => node.scrollIntoView({ block: 'start' }));
  const group = process.env.MEDCOM_CAPTURE_GROUP;
  if (!group || group === 'purchase') {
    await visit('purchase-requests');
    await capture('pr-list', [button('Tạo mới'), page.getByRole('button', { name: /Mới lập/ }), page.getByText('PR-MINH-HOA-001', { exact: true }).filter({visible:true}).first()], true);
    await button('Tạo mới').click();
    await page.getByText('Tạo đề nghị mua hàng', { exact: true }).waitFor();
    await page.locator('input[type="date"]').first().fill('2026-10-19');
    await capture('pr-header', [field('Người đề nghị'), field('Bộ phận')]);
    await select('Người đề nghị', 'Người đề nghị minh họa', true);
    await select('Bộ phận', 'Bộ phận minh họa', true);
    await select('Khách hàng', 'Khách hàng minh họa');
    if (device === 'mobile') await button('2. Chi tiết').click();
    await select('Mã hàng', 'Vật tư xét nghiệm minh họa');
    await fillField('Số lượng', '2'); await fillField('Đơn giá', '150000');
    await top(button('Thêm dòng'));
    await capture('pr-lines', [button('Thêm dòng'), field('Mã hàng'), page.getByRole('dialog').last().locator('label').filter({hasText:'Số lượng'}).first().locator('..').locator('input').first()]);
    if (device === 'mobile') await button('Xem lại').click();
    await top(page.getByRole('heading', {name:device==='mobile'?'Xem lại':'Tổng hợp',exact:true}));
    await capture('pr-review', [button('Xác nhận tạo phiếu')]);
    await visit('purchase-requests', true);
    await button('Thao tác chứng từ').click();
    await capture('pr-actions', [button('Thao tác chứng từ'), button('Gửi đề nghị')]);
    await button('Sửa thông tin').click();
    await page.getByText('Sửa đề nghị mua hàng', { exact: true }).waitFor();
    await capture('pr-edit', [field('Người đề nghị')]);
    await visit('purchase-approvals');
    await capture('approval-list', [page.getByRole('button', { name: /Chờ duyệt/ }), page.getByText('PR-MINH-HOA-001', { exact: true }).filter({visible:true}).first()], true);
    await page.getByText('PR-MINH-HOA-001', { exact: true }).filter({visible:true}).first().click();
    await button('Thao tác chứng từ').click();
    await capture('approval-menu', [button('Duyệt'), button('Không duyệt')]);
    await button('Duyệt').click();
    await button('Xác nhận Duyệt').waitFor();
    await capture('approval-confirm', [page.locator('textarea'), button('Xác nhận Duyệt')]);
    await button('Hủy').last().click();
    await button('Thao tác chứng từ').click(); await button('Không duyệt').click();
    await page.locator('textarea').fill('Vui lòng kiểm tra số lượng và bổ sung thời gian cần hàng.');
    await capture('approval-reject', [page.locator('textarea'), button('Xác nhận Không duyệt')]);
    await visit('purchase-orders');
    await capture('po-list', [page.getByPlaceholder('Tìm theo mã chứng từ, người lập, đối tượng...'), page.getByRole('button', { name: /Đang mở \/ Chưa khóa/ }), page.getByText('PO-MINH-HOA-001', { exact: true }).filter({visible:true}).first()], true);
    await page.getByText('PO-MINH-HOA-001', { exact: true }).filter({visible:true}).first().click();
    await page.getByText('Nhà cung cấp minh họa', { exact: true }).last().waitFor();
    await capture('po-detail', [page.getByText('Nhà cung cấp minh họa', { exact: true }).last()]);
  }
  if (!group || group === 'sales') {
    if (process.env.MEDCOM_CAPTURE_SCENES !== 'qr') {
    await visit('sales-orders');
    await page.getByLabel('Lọc trạng thái đơn hàng').waitFor();
    await page.getByLabel('Lọc trạng thái đơn hàng').selectOption({ label: 'Mới lập' });
    await capture('so-list', [page.getByPlaceholder('Tìm theo mã chứng từ, người lập, đối tượng...'), page.getByLabel('Lọc trạng thái đơn hàng'), page.getByText('DH-MINH-HOA-001', { exact: true }).filter({visible:true}).first()], true);
    await button('Tạo mới').click();
    await page.getByText('Tạo đơn hàng', { exact: true }).waitFor();
    await page.locator('input[type="date"]').first().fill('2026-10-19');
    await capture('so-create', [field('Khách hàng')]);
    await select('Khách hàng', 'Khách hàng minh họa');
    await select('Mã nhân viên', 'Nhân viên minh họa');
    await select('Mã hợp đồng', 'Hợp đồng minh họa');
    if (device === 'mobile') await button('Tiếp: Chi tiết').click();
    await select('Mã hàng', 'Vật tư xét nghiệm minh họa');
    await page.getByRole('textbox', { name: 'Số lượng dòng 1', exact: true }).fill('2');
    await page.getByRole('textbox', { name: 'Đơn giá dòng 1', exact: true }).fill('150000');
    await top(button('Thêm dòng')); await capture('so-lines', [field('Mã hàng')]);
    if (device === 'mobile') await button('Xem lại').click();
    else await button('Xác nhận tạo đơn').scrollIntoViewIfNeeded();
    await capture('so-review', [button('Xác nhận tạo đơn')]);
    await visit('sales-orders', true);
    await capture('so-detail', [page.locator('[data-sales-order-overview]').getByText('Khách hàng minh họa', { exact: false }).last()]);
    await button('Sửa').click(); await field('Khách hàng').waitFor();
    await capture('so-edit', [field('Khách hàng')]);
    await visit('sales-orders', true);
    const history = page.getByRole('tab', { name: /Lịch sử gửi/ });
    await history.click(); await top(history); await capture('so-history', [history]);
    await button('Gửi PM').click();
    await page.getByRole('radio', { name: 'PM minh họa' }).click();
    await capture('so-send', [page.getByRole('radio', { name: 'PM minh họa' }), page.getByText('Đã chọn: PM minh họa', { exact: true }), button('Xác nhận')]);
    await visit('sales-order-pm', true);
    await capture('pm-detail', [button('Gửi SA')]); await button('Gửi SA').click();
    await capture('pm-send', [page.getByRole('dialog').last().locator('textarea'), button('Xác nhận')]);
    await button('Hủy').last().click(); await button('Trả lại').click();
    await page.getByRole('dialog').last().locator('textarea').fill('Vui lòng kiểm tra số lượng và lịch giao hàng.');
    await capture('pm-reject', [page.getByRole('dialog').last().locator('textarea'), button('Xác nhận')]);
    await visit('sales-order-sa', true);
    await capture('sa-detail', [button('Gửi Kế toán')]); await button('Gửi Kế toán').click();
    await capture('sa-route', [page.getByRole('dialog').last().locator('textarea'), button('Xác nhận')]);
    await button('Hủy').last().click(); await button('Gửi về bước trước').click();
    await page.getByRole('radio', { name: 'Gửi về PM kiểm tra' }).click();
    await capture('sa-return', [page.getByRole('radio', { name: 'Gửi về PM kiểm tra' }), button('Xác nhận')]);
    }
    await visit('sales-qr', true);
    await capture('qr-detail', [button('Quét thêm mã QR'), button('Quét xóa mã QR')]);
    await button('Quét thêm mã QR').click();
    await page.getByPlaceholder('Mã ItemID;ItemCode;Lot hoặc PKG1;...').waitFor();
    await page.getByText('Đang mở máy ảnh...', {exact:true}).waitFor({state:'hidden'});
    await page.getByPlaceholder('Mã ItemID;ItemCode;Lot hoặc PKG1;...').fill('HH-DEMO-01;HH-DEMO-01;LO-DEMO');
    await capture('qr-scan', [page.getByPlaceholder('Mã ItemID;ItemCode;Lot hoặc PKG1;...'), button('Xác nhận')]);
    await visit('sales-qr', true);
    const comparison = page.getByText('Dòng đối chiếu hàng cần quét (1)', { exact: true });
    await top(comparison); await capture('qr-compare', [comparison]);
  }
}
