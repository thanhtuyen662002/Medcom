import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const url='https://api-medcom.bms79.com/api/contracts/openapi.json';
const response=await fetch(url,{signal:AbortSignal.timeout(60000),redirect:'error'});
if(!response.ok)throw new Error('Contract download failed: HTTP '+response.status);
const bytes=Buffer.from(await response.arrayBuffer());
if(bytes.length>15*1024*1024)throw new Error('Unexpected contract size');
const spec=JSON.parse(bytes);
if(!spec.openapi?.startsWith('3.')||!spec.paths||!spec.components?.schemas)throw new Error('Unsupported contract');
const operations=Object.values(spec.paths).flatMap(item=>Object.entries(item).filter(([method])=>['get','post','put','patch','delete','head','options'].includes(method)));
if(operations.some(([,op])=>!op.operationId))throw new Error('Missing operationId');
const provenance={url,fetchedAt:new Date().toISOString(),sha256:crypto.createHash('sha256').update(bytes).digest('hex'),bytes:bytes.length,version:spec.info.version,operations:operations.length,paths:Object.keys(spec.paths).length,schemas:Object.keys(spec.components.schemas).length};
await fs.mkdir(path.join(root,'contracts'),{recursive:true});
await fs.writeFile(path.join(root,'contracts/openapi.json'),bytes);
await fs.writeFile(path.join(root,'contracts/provenance.json'),JSON.stringify(provenance,null,2)+'\n');
console.log(JSON.stringify(provenance));
