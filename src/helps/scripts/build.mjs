import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const catalog = JSON.parse(await readFile(path.join(root, 'content/catalog.json'), 'utf8'));
const ids = new Set();
for (const article of catalog.articles) {
  if (!/^[a-z][a-z0-9-]+$/.test(article.id) || ids.has(article.id)) throw new Error('Invalid/duplicate article ID');
  ids.add(article.id);
  for (const field of ['guide', 'technical']) {
    const target = path.resolve(root, 'content', article[field]);
    if (!target.startsWith(path.join(root, 'content') + path.sep)) throw new Error('Content path escapes content directory');
    article[field] = (await readFile(target, 'utf8')).replace(/\r\n?/g, '\n');
    if (!article[field].includes('## ')) throw new Error(`Empty article: ${article.id}`);
  }
}
if (!ids.has(catalog.defaultArticle)) throw new Error('Missing default article');
for (const article of catalog.articles) {
  for (const match of (article.guide + article.technical).matchAll(/\]\(#([a-z][a-z0-9-]+)\)/g)) {
    if (!ids.has(match[1])) throw new Error(`Broken article link: ${match[1]}`);
  }
}
await mkdir(path.join(root, 'assets'), { recursive: true });
const audiences = {
  guide: {
    title: 'Hướng dẫn sử dụng', contentFile: 'content.generated.js',
    description: 'Hướng dẫn thao tác ERP Medcom: mua hàng, nhập hàng, bán hàng, điều chuyển, tài sản và linh kiện.',
    searchPlaceholder: 'Tìm quy trình, bước thao tác, nút bấm…',
    searchHint: 'Tìm theo tên quy trình hoặc thao tác, có thể gõ tiếng Việt không dấu.'
  },
  technical: {
    title: 'Tài liệu kỹ thuật', contentFile: 'technical.generated.js',
    description: 'Luồng xử lý, liên kết dữ liệu và đối tượng kỹ thuật ERP Medcom dành cho đội phát triển.',
    searchPlaceholder: 'Tìm luồng xử lý, tên form, STP, view…',
    searchHint: 'Tìm theo luồng, tên form hoặc đối tượng DB, có thể gõ tiếng Việt không dấu.'
  }
};
for (const [mode, audience] of Object.entries(audiences)) {
  const articles = catalog.articles.map(article => {
    const { guide, technical, errors, forms, objects, ...shared } = article;
    return mode === 'guide' ? { ...shared, guide, errors } : { ...shared, technical, forms, objects };
  });
  const payload = JSON.stringify({ ...catalog, articles }).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  await writeFile(path.join(root, 'assets', audience.contentFile), `/* Generated by scripts/build.mjs. Edit content/ instead. */\nwindow.MEDCOM_DOCS = ${payload};\n`);
}
const template = await readFile(path.join(root, 'scripts/shell.html'), 'utf8');
for (const [folder, mode, prefix] of [['', 'guide', './'], ['HDSD-ERP', 'guide', '../'], ['TLKT', 'technical', '../']]) {
  await mkdir(path.join(root, folder), { recursive: true });
  const audience = audiences[mode];
  await writeFile(path.join(root, folder, 'index.html'), template.replaceAll('{{ROOT}}', prefix).replaceAll('{{MODE}}', mode).replaceAll('{{TITLE}}', audience.title).replaceAll('{{DESCRIPTION}}', audience.description).replaceAll('{{CONTENT_FILE}}', audience.contentFile).replaceAll('{{SEARCH_PLACEHOLDER}}', audience.searchPlaceholder).replaceAll('{{SEARCH_HINT}}', audience.searchHint));
}
console.log(`Built ${catalog.articles.length} guides + ${catalog.articles.length} technical articles; 3 static entry points.`);
